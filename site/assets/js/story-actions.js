(() => {
  'use strict';

  function initStoryActions() {
    const main = document.querySelector('.reader-main');
    const content = document.querySelector('#reader-content');
    if (!main || !content || document.querySelector('#story-actions')) return;

    const payloadElement = document.querySelector('#story-payload');
    if (!payloadElement) return;

    let payload;
    try {
      payload = JSON.parse(payloadElement.textContent);
    } catch {
      return;
    }

    const slug = payload.story?.slug || location.pathname;
    const title = payload.story?.title || {};
    const getTitle = () =>
      document.documentElement.lang === 'kn'
        ? (title.kn || title.en || 'Katha Loka')
        : (title.en || 'Katha Loka');

    const bar = document.createElement('section');
    bar.id = 'story-actions';
    bar.className = 'story-actions';
    bar.setAttribute('aria-label', 'Story actions');

    const like = document.createElement('button');
    like.type = 'button';
    like.className = 'story-action';
    like.setAttribute('aria-pressed', 'false');

    const share = document.createElement('button');
    share.type = 'button';
    share.className = 'story-action';
    share.textContent = '↗ Share';

    const qrToggle = document.createElement('button');
    qrToggle.type = 'button';
    qrToggle.className = 'story-action';
    qrToggle.textContent = '▦ Scan QR';

    const qrPanel = document.createElement('div');
    qrPanel.className = 'story-qr-panel';
    qrPanel.hidden = true;

    const qrHeading = document.createElement('p');
    qrHeading.textContent = 'Scan to read this story';

    const qrImage = document.createElement('img');
    qrImage.alt = 'QR code linking to this story';
    qrImage.width = 200;
    qrImage.height = 200;
    qrImage.loading = 'lazy';

    const qrLink = document.createElement('a');
    qrLink.href = location.href;
    qrLink.textContent = 'Open story link';
    qrLink.target = '_blank';
    qrLink.rel = 'noopener noreferrer';

    const qrNote = document.createElement('small');
    qrNote.textContent =
      'The QR image is generated by a third-party QR service.';

    qrPanel.append(qrHeading, qrImage, document.createElement('br'), qrLink, document.createElement('br'), qrNote);
    bar.append(like, share, qrToggle);
    main.insertBefore(bar, content);
    main.insertBefore(qrPanel, content);

    const storageKey = 'katha-liked:' + slug;

    function refreshLike() {
      let liked = false;
      try {
        liked = localStorage.getItem(storageKey) === 'true';
      } catch {}

      like.setAttribute('aria-pressed', String(liked));
      like.textContent = liked ? '♥ Liked' : '♡ Like';
      like.classList.toggle('is-liked', liked);
    }

    like.addEventListener('click', () => {
      try {
        const next = like.getAttribute('aria-pressed') !== 'true';
        localStorage.setItem(storageKey, String(next));
        refreshLike();
      } catch {
        alert('Likes could not be saved in this browser.');
      }
    });

    share.addEventListener('click', async () => {
      const shareData = { title: getTitle(), url: location.href };

      try {
        if (navigator.share) {
          await navigator.share(shareData);
        } else if (navigator.clipboard?.writeText) {
          await navigator.clipboard.writeText(location.href);
          share.textContent = '✓ Link copied';
          setTimeout(() => { share.textContent = '↗ Share'; }, 1800);
        } else {
          window.prompt('Copy this story link:', location.href);
        }
      } catch (error) {
        if (error?.name !== 'AbortError') {
          window.prompt('Copy this story link:', location.href);
        }
      }
    });

    qrToggle.addEventListener('click', () => {
      qrPanel.hidden = !qrPanel.hidden;
      qrToggle.setAttribute('aria-expanded', String(!qrPanel.hidden));

      if (!qrPanel.hidden) {
        const url = location.href;
        qrLink.href = url;
        qrImage.src =
          'https://api.qrserver.com/v1/create-qr-code/?size=200x200&data=' +
          encodeURIComponent(url);
      }
    });

    refreshLike();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initStoryActions, { once: true });
  } else {
    initStoryActions();
  }
})();
